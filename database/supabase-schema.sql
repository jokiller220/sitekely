begin;

create table if not exists public.users (
  id bigint generated by default as identity primary key,
  first_name text not null,
  last_name text not null,
  email text not null unique,
  password_hash text not null,
  role text not null default 'student' check (role in ('student','teacher','admin')),
  bio text not null default '',
  status text not null default 'active' check (status in ('active','suspended')),
  avatar_path text,
  last_login_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name text not null unique,
  description text not null default '',
  icon text not null default 'library',
  is_active boolean not null default true,
  sort_order integer not null default 0,
  position integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.media (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  type text not null check (type in ('video','podcast')),
  title text not null,
  description text not null default '',
  category text not null,
  visibility text not null default 'public' check (visibility in ('public','unlisted','private')),
  status text not null default 'published' check (status in ('draft','pending','published','hidden','archived','failed')),
  file_path text,
  original_name text,
  mime_type text,
  size bigint,
  views_count bigint not null default 0,
  thumbnail_path text,
  duration_seconds integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.favorites (
  user_id bigint not null references public.users(id) on delete cascade,
  media_id bigint not null references public.media(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, media_id)
);

create table if not exists public.shares (
  id bigint generated by default as identity primary key,
  media_id bigint not null references public.media(id) on delete cascade,
  token text not null unique,
  expires_at timestamptz,
  revoked_at timestamptz,
  views_count bigint not null default 0,
  created_by bigint not null references public.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  type text not null default 'info',
  title text not null,
  message text not null,
  link text,
  read_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.reports (
  id bigint generated by default as identity primary key,
  reporter_id bigint references public.users(id) on delete set null,
  user_id bigint references public.users(id) on delete set null,
  media_id bigint not null references public.media(id) on delete cascade,
  reason text not null,
  details text not null default '',
  status text not null default 'pending',
  action_taken text not null default '',
  resolved_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.password_resets (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  token text not null unique,
  expires_at timestamptz not null,
  used_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.contact_messages (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  subject text not null default 'Général',
  message text not null,
  is_read boolean not null default false,
  created_at timestamptz not null default now()
);

create index if not exists media_user_id_idx on public.media(user_id);
create index if not exists media_catalog_idx on public.media(type, status, visibility, created_at desc);
create index if not exists notifications_user_unread_idx on public.notifications(user_id, read_at, created_at desc);
create index if not exists shares_token_idx on public.shares(token);
create index if not exists reports_status_idx on public.reports(status, created_at desc);

-- Defense in depth: public is an exposed schema in Supabase. The PHP backend
-- will use a server-only database connection; browser roles receive no policy
-- and therefore no direct row access through the Data API.
alter table public.users enable row level security;
alter table public.categories enable row level security;
alter table public.media enable row level security;
alter table public.favorites enable row level security;
alter table public.shares enable row level security;
alter table public.notifications enable row level security;
alter table public.reports enable row level security;
alter table public.password_resets enable row level security;
alter table public.contact_messages enable row level security;

